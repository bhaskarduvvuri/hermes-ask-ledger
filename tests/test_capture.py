import unittest
from unittest import mock

from plugin.capture import extract_text, is_user_turn, one_line


class ExtractTextTest(unittest.TestCase):
    def test_string(self):
        self.assertEqual(extract_text("  hello there \n"), "hello there")

    def test_multimodal_parts(self):
        parts = [{"type": "image_url", "image_url": {"url": "data:..."}},
                 {"type": "text", "text": "what is this"},
                 {"type": "text", "text": "and this"}]
        self.assertEqual(extract_text(parts), "what is this\nand this")

    def test_image_only(self):
        self.assertEqual(extract_text([{"type": "image_url", "image_url": {}}]), "")

    def test_garbage(self):
        self.assertEqual(extract_text(None), "")
        self.assertEqual(extract_text(42), "")
        self.assertEqual(extract_text([None, 3, {"type": "text"}]), "")


class IsUserTurnTest(unittest.TestCase):
    def kw(self, **over):
        base = {"platform": "cli", "parent_session_id": "", "user_message": "hi"}
        base.update(over)
        return base

    def test_plain_cli_turn(self):
        with mock.patch.dict("os.environ", {}, clear=True):
            self.assertTrue(is_user_turn(**self.kw()))

    def test_gateway_turn(self):
        with mock.patch.dict("os.environ", {}, clear=True):
            self.assertTrue(is_user_turn(**self.kw(platform="telegram")))

    def test_cron_and_subagent(self):
        self.assertFalse(is_user_turn(**self.kw(platform="cron")))
        self.assertFalse(is_user_turn(**self.kw(platform="subagent")))

    def test_child_agent(self):
        self.assertFalse(is_user_turn(**self.kw(parent_session_id="s-parent")))

    def test_kanban_worker(self):
        with mock.patch.dict("os.environ", {"HERMES_KANBAN_TASK": "t1"}):
            self.assertFalse(is_user_turn(**self.kw()))

    def test_empty_message(self):
        self.assertFalse(is_user_turn(**self.kw(user_message="   ")))

    def test_slash_command_text(self):
        self.assertFalse(is_user_turn(**self.kw(user_message="/asks")))

    def test_machine_written_text(self):
        footer = "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]"
        with mock.patch.dict("os.environ", {}, clear=True):
            self.assertFalse(is_user_turn(**self.kw(user_message="Process done\n\n" + footer)))
            self.assertFalse(is_user_turn(**self.kw(user_message="[SYSTEM NOTICE — budget] stop soon")))
            self.assertFalse(is_user_turn(**self.kw(user_message=[{"type": "text", "text": "[SYSTEM] x"}])))
            self.assertTrue(is_user_turn(**self.kw(user_message="What does [SYSTEM] mean in logs?")))


class OneLineTest(unittest.TestCase):
    def test_collapses_and_cuts(self):
        self.assertEqual(one_line("a\n\n b\tc", 100), "a b c")
        out = one_line("x" * 50, 10)
        self.assertEqual(len(out), 10)
        self.assertTrue(out.endswith("…"))


if __name__ == "__main__":
    unittest.main()
