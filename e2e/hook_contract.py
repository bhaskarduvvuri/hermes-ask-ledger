"""Hook-contract checks against a real Hermes install (run by e2e/run.sh).

Loads the installed, enabled plugin through Hermes's own plugin manager and fires
Hermes's own hook dispatch with gateway-shaped payloads. It checks:
  1. an admitted gateway message becomes exactly one ask, and the admission hook never
     consumes the message;
  2. a gateway wake event (an agent turn with no admission: background result,
     automation) creates no ask but still receives the reminder;
  3. a gateway-owned local session ("local" platform) is captured once, not twice;
  4. a local wake event carrying this release's internal-notification footer is no ask;
  5. a webhook delivery (platform "webhook") is no ask;
  6. resending the same words (/retry, rewind + resend) does not add a second ask.
It does not start a messaging gateway (the test machine has no platform network),
so it proves the plugin's side of the contract, not the gateway's routing.
All messages are invented. Exit 0 = all passed.
"""

import asyncio
import json
import os
import sys
from pathlib import Path

from hermes_cli.lifecycle import ainvoke_hook, has_hook, invoke_hook
from hermes_cli.plugins import discover_plugins

LEDGER = Path(os.environ["HERMES_HOME"]) / "plugin-data" / "ask-ledger" / "asks.jsonl"
FAILED = []


def check(name, ok, detail=""):
    print(("PASS " if ok else "FAIL ") + name + (f" ({detail})" if detail and not ok else ""))
    if not ok:
        FAILED.append(name)


def ask_count():
    if not LEDGER.exists():
        return 0
    return sum(1 for line in LEDGER.read_text().splitlines()
               if line.strip() and json.loads(line).get("op") == "new")


def turn(text, platform, sender, session):
    return invoke_hook("pre_llm_call", session_id=session, task_id="e2e", turn_id="e2e",
                       user_message=text, conversation_history=[], is_first_turn=False,
                       model="e2e", platform=platform, parent_session_id="", sender_id=sender)


def admit(text, platform, user_id):
    return asyncio.run(ainvoke_hook(
        "post_gateway_admission", session_key=f"agent:main:{platform}:dm:e2e-chat", platform=platform,
        source={"platform": platform, "chat_id": "e2e-chat", "user_id": user_id},
        message_id="e2e-1", text=text))


def main():
    discover_plugins(force=True)
    check("pre_llm_call registered", has_hook("pre_llm_call"))
    check("post_gateway_admission registered", has_hook("post_gateway_admission"))

    # 1. Gateway message
    before = ask_count()
    results = admit("Invented ask: suggest three easy houseplants.", "telegram", "e2e-user")
    check("admission never consumes", not any(isinstance(r, dict) and r.get("action") == "handled"
                                              for r in results), repr(results))
    turn("Invented ask: suggest three easy houseplants.", "telegram", "e2e-user", "e2e-gw")
    check("gateway message -> exactly one ask", ask_count() == before + 1, f"{before} -> {ask_count()}")

    # 2. Wake event: agent turn, no admission
    before = ask_count()
    ctx = turn("Background process 7 finished with exit code 0.", "telegram", "e2e-user", "e2e-gw")
    check("wake event -> no ask", ask_count() == before, f"{before} -> {ask_count()}")
    joined = " ".join(r["context"] for r in ctx if isinstance(r, dict) and r.get("context"))
    # run.sh sets remind_after_minutes to 0 before this script, so the seconds-old ask is due.
    check("wake event still gets reminder", "houseplants" in joined, f"context was {joined[:200]!r}")

    # 3. Gateway-owned local session: both hooks may fire, one ask
    before = ask_count()
    admit("Invented ask: name a small cactus.", "local", "e2e-local")
    turn("Invented ask: name a small cactus.", "local", "", "e2e-local-session")
    check("local session -> exactly one ask", ask_count() == before + 1, f"{before} -> {ask_count()}")

    # 4. Local wake event: Hermes's real internal-notification footer for this release.
    try:
        from gateway.run_notifications import INTERNAL_NOTIFICATION_FOOTER as footer
        footer_source = "imported"
    except Exception:
        footer = "[INTERNAL NOTIFICATION — generated by the Hermes gateway, not written by a human user.]"
        footer_source = "literal fallback"
    print(f"footer: {footer_source}")
    before = ask_count()
    turn("Background process 9 finished with exit code 0.\n\n" + footer, "local", "", "e2e-local-session")
    check("local wake event -> no ask", ask_count() == before, f"{before} -> {ask_count()}")

    # 5. Webhook producers reach admission but are machines.
    before = ask_count()
    admit("Invented webhook: build 42 failed.", "webhook", "e2e-hook")
    check("webhook -> no ask", ask_count() == before, f"{before} -> {ask_count()}")

    # 6. /retry or rewind-and-resend replays the same words: no second ask.
    before = ask_count()
    turn("Invented ask: name a small cactus.", "local", "", "e2e-local-session")
    check("resend same words -> no new ask", ask_count() == before, f"{before} -> {ask_count()}")

    print(f"{len(FAILED)} failed")
    return 1 if FAILED else 0


if __name__ == "__main__":
    sys.exit(main())
